const LOCALE: Record<Lang, string> = { en: "en-GB", de: "de-DE" };

function makeTools(lang: Lang) {
  const money = new Intl.NumberFormat(lang === "de" ? "de-DE" : "en-IE", { style: "currency", currency: "EUR" });
  const dateFormat = new Intl.DateTimeFormat(LOCALE[lang], lang === "de" ? { day: "2-digit", month: "2-digit", year: "numeric" } : { day: "numeric", month: "short", year: "numeric" });
  const timeFormat = new Intl.DateTimeFormat(LOCALE[lang], { day: "2-digit", month: "2-digit", year: "numeric", hour: "2-digit", minute: "2-digit" });

  const t = (key: Key, vars?: Record<string, string | number>): string => {
    let text = DICTIONARY[lang][key];
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };

  return {
    lang,
    t,
    labels: LABELS[lang],
    eur: (cents: number) => money.format((cents || 0) / 100),
    day: (iso?: string | null) => {
      if (!iso) return "-";
      const [year, month, date] = iso.slice(0, 10).split("-").map(Number);
      return dateFormat.format(new Date(year, month - 1, date));
    },
    dateTime: (iso?: string | null) => (iso ? timeFormat.format(new Date(iso)) : "-"),
    daysLate: (days: number) => (days === 1 ? t("daysLateOne") : t("daysLate", { n: days })),
    invoiceCount: (count: number) => (count === 1 ? t("invoiceCountOne") : t("invoiceCount", { n: count })),
    duration: (seconds: number) => (seconds < 120 ? t("seconds", { n: seconds }) : t("minutes", { n: Math.round(seconds / 60) })),
  };
}

export type Tools = ReturnType<typeof makeTools>;

type Context = Tools & { setLang: (lang: Lang) => void };

const LangContext = createContext<Context | null>(null);

function firstLanguage(): Lang {
  const stored = window.localStorage.getItem("paidloop.language");
  if (stored === "de" || stored === "en") return stored;
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(firstLanguage);
  // Set during render, because child pages start loading before any effect here would run.
  setApiLanguage(lang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((value: Lang) => {
    window.localStorage.setItem("paidloop.language", value);
    setLangState(value);
  }, []);

  const value = useMemo(() => ({ ...makeTools(lang), setLang }), [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useT(): Context {
  const value = useContext(LangContext);
  if (!value) throw new Error("useT needs LangProvider");
  return value;
}

/** For the customer page, whose language follows the customer rather than the owner's choice. */
export const toolsFor = (lang: Lang) => makeTools(lang);
